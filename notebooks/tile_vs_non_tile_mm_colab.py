import subprocess
import pandas as pd
import io
import matplotlib.pyplot as plt

# Execute the 16K benchmark binary
result = subprocess.run(['./run_benchmark'], capture_output=True, text=True)

# Parse stdout stream data lines into a pandas frame
df = pd.read_csv(io.StringIO(result.stdout))

# Configure plot sizes
plt.figure(figsize=(12, 6))
plt.plot(df['Size'], df['Tiled_ms'], marker='o', linewidth=2.5, color='#1f77b4', label='Tiled (Shared Memory Access)')
plt.plot(df['Size'], df['Naive_ms'], marker='s', linewidth=2.5, color='#d62728', label='Naive (Global Memory Access)')

# Apply a Logarithmic Scale to the Y-axis to handle the massive performance delta
plt.yscale('log')

plt.title('CUDA Matrix Multiplication 16K Scale Comparison (NVIDIA T4)', fontsize=14, fontweight='bold')
plt.xlabel('Matrix Scale Dimension (N x N)', fontsize=12)
plt.ylabel('Execution Duration Log Scale (ms)', fontsize=12)
plt.grid(True, which="both", linestyle='--', alpha=0.5)
plt.xticks(df['Size'])
plt.legend(fontsize=12)

# Present output plot canvas
plt.show()

print("\n16K Matrix Scaling Performance Records:")
print(df.to_string(index=False))

